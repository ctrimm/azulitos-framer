#!/usr/bin/env python3
"""Generate all 72 Azulitos tiles and their exports.

    python3 scripts/build.py

Writes (all build artifacts — never hand-edit them; fix the generator instead):
  assets/svg/AZL-NN.svg        vector tile, motif on transparency
  assets/png-1000/AZL-NN.png   1000 px, transparent
  assets/png-2000/AZL-NN.png   2000 px, transparent
  framer/tiles/AZL-NN.json     shape list consumed by the Framer build
  framer/manifest.json         ids, names, groups, families
  TILES.md                     the catalogue
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))

from azulitos.designs import FAMILIES, PadraoSpec, catalogue  # noqa: E402
from azulitos.export import svg_to_png, to_framer, to_svg, write_json  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def main():
    dirs = {k: os.path.join(ROOT, *k.split("/")) for k in
            ("assets/svg", "assets/png-1000", "assets/png-2000", "framer/tiles")}
    for d in dirs.values():
        os.makedirs(d, exist_ok=True)

    manifest = []
    for tile, builder, spec in catalogue():
        layers = builder()
        svg = to_svg(tile, layers)
        with open(os.path.join(dirs["assets/svg"], f"{tile.id}.svg"), "w") as f:
            f.write(svg)
        svg_to_png(svg, 1000).save(os.path.join(dirs["assets/png-1000"], f"{tile.id}.png"), optimize=True)
        svg_to_png(svg, 2000).save(os.path.join(dirs["assets/png-2000"], f"{tile.id}.png"), optimize=True)
        fj = to_framer(tile, layers)
        write_json(os.path.join(dirs["framer/tiles"], f"{tile.id}.json"), fj)
        family = spec.corner if (tile.group == "Padrão" and isinstance(spec, PadraoSpec)) else None
        manifest.append({"id": tile.id, "name": tile.name, "group": tile.group, "motifs": tile.motifs,
                         "family": family, "shapes": len(fj["shapes"]),
                         "holes": sum(len(s["holes"]) for s in fj["shapes"]),
                         "colours": sorted({s["fill"] for s in fj["shapes"]})})
        print(tile.id, tile.name, f'{len(fj["shapes"])} shapes', flush=True)

    with open(os.path.join(ROOT, "framer", "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=1, ensure_ascii=False)
    write_tiles_md(manifest)


def write_tiles_md(manifest):
    groups = {"Padrão": "AZL-01…48 — Padrão (cobalt, seamless)",
              "Medalhão": "AZL-49…64 — Medalhão (cobalt, standalone)",
              "Polícromo": "AZL-65…72 — Polícromo (Lisbon palette, seamless)"}
    lines = ["# Tiles — Azulitos", "",
             "Generated by `scripts/build.py` — do not edit by hand. Framer item name = `<id> <name>`.", "",
             "Every Padrão tile belongs to a **family** (its corner motif). The six tiles in a family share",
             "every element that crosses the tile edge, so they can be mixed freely in one seamless panel.", ""]
    lines += ["| Family | Edge motif | Frame | Tiles |", "|---|---|---|---|"]
    for corner, (edge, frame, _rc) in FAMILIES.items():
        ids = [m["id"] for m in manifest if m["family"] == corner]
        lines.append(f"| {corner} | {edge} | {frame} | {ids[0]}…{ids[-1][-2:]} |")
    for g, title in groups.items():
        lines += ["", f"## {title}", "", "| ID | Name | Group | Dominant motifs | Family |", "|---|---|---|---|---|"]
        for m in manifest:
            if m["group"] == g:
                lines.append(f"| {m['id']} | {m['name']} | {g} | {', '.join(m['motifs'])} | {m['family'] or '—'} |")
    counts = {g: sum(1 for m in manifest if m["group"] == g) for g in groups}
    lines += ["", f"**Total: {len(manifest)}** — " + ", ".join(f"{g} {n}" for g, n in counts.items()), ""]
    with open(os.path.join(ROOT, "TILES.md"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
